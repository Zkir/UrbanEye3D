#!/usr/bin/env python3
"""Generate data/17_seedthree_textures/assets_trees.mapcss (stage 17, assets step).

One rule per species whose Latin binomial is in data/15_trees_output/tree_species.csv,
plus extra selectors for its POWO synonyms from data/15_trees_output/tree_synonyms.csv.
Copying PNGs and the mapcss into src/ is done by the Makefile, not here.
Run make_tree_billboards.py first; make runs both stages in order.
Prints AssetListTest provenance lines for the new textures.
"""
import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
DATA = REPO / "misc" / "data" / "17_seedthree_textures"
SPECIES_JSON = DATA / "intermediates" / "species.json"
MANIFEST = DATA / "manifest.json"
TREE_SPECIES_CSV = REPO / "misc" / "data" / "15_trees_output" / "tree_species.csv"
TREE_SYNONYMS_CSV = REPO / "misc" / "data" / "15_trees_output" / "tree_synonyms.csv"
ASSETS_TREES = DATA / "assets_trees.mapcss"
MARK_BEGIN = ("/* BEGIN GENERATED by misc/tree_billboards/make_tree_assets.py"
              " \u2014 do not edit by hand */")
MARK_END = "/* END GENERATED by misc/tree_billboards/make_tree_assets.py */"
HYBRID = "\u00d7"


def latin_slug(name):
    return re.sub(r"[^A-Za-z0-9]+", "_", name.strip())


def norm_key(name):
    """Mirror of TreeSpeciesDatabase.normalizeSpecies: the form tags take at match time."""
    trimmed = name.strip()
    if re.match(r"^[A-Z][a-z]+\s+'[A-Z].*'$", trimmed):
        return trimmed.split(" ")[0].lower() + " sp."
    n = trimmed.lower()
    n = re.sub(r"(^|\s)x(\s|$)", " " + HYBRID + " ", n).strip()
    n = re.sub(r"\s*" + HYBRID + r"\s*", " " + HYBRID + " ", n)
    n = re.sub(r"\s+", " ", n).strip()
    parts = n.split(" ")
    if len(parts) < 2:
        return n
    if HYBRID in parts[:3]:
        keep = 4 if parts.index(HYBRID) == 2 else 3
        return " ".join(parts[:keep])
    return " ".join(parts[:2])


def formatted(key):
    """Mirror of formatSpecies: genus capitalized, rest as normalized."""
    parts = key.split(" ")
    if parts[0] == HYBRID and len(parts) > 1:
        parts[1] = parts[1][0].upper() + parts[1][1:]
    else:
        parts[0] = parts[0][0].upper() + parts[0][1:]
    return " ".join(parts)


def is_binomial(key):
    parts = key.split(" ")
    return len(parts) >= 2 and parts[-1] != "sp."


def load_master_keys():
    with open(TREE_SPECIES_CSV, encoding="utf-8-sig") as f:
        return {norm_key(row[0]) for row in csv.reader(f) if row and row[0].strip()}


def load_synonyms():
    """key -> alternative keys, accepted<->synonym in both directions."""
    syn = defaultdict(list)
    with open(TREE_SYNONYMS_CSV, encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            a, s = norm_key(row["accepted_name"]), norm_key(row["species"])
            if is_binomial(a) and is_binomial(s):
                syn[a].append(s)
                syn[s].append(a)
    return syn


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--variant", default="01",
                        help="variant suffix to promote")
    args = parser.parse_args()

    for path in (SPECIES_JSON, MANIFEST, TREE_SPECIES_CSV, TREE_SYNONYMS_CSV):
        if not path.exists():
            sys.exit(f"{path} not found: run the earlier pipeline stages first")
    with open(SPECIES_JSON, encoding="utf-8") as f:
        species = json.load(f)
    with open(MANIFEST, encoding="utf-8") as f:
        manifest_all = json.load(f)
    manifest = manifest_all["entries"]
    known = load_master_keys()
    syn = load_synonyms()

    rules = [MARK_BEGIN,
             f"/* SeedThree procedural tree billboards, SeedThree rev "
             f"{str(manifest_all.get('rev', '?'))[:8]}, variant _{args.variant}. "
             f"Latin names + synonyms (tree_synonyms.csv); textures under "
             f"/textures/trees/. Provenance: AssetListTest. */"]
    textures = []
    claimed = {}
    total_selectors = 0
    for sp in species:
        latin = sp.get("latin") or sp["name"]
        key = norm_key(latin)
        texture = f"{latin_slug(latin)}_{args.variant}.png"
        if not (DATA / texture).exists():
            print(f"skip {sp['key']}: {texture} not baked yet")
            continue
        textures.append(texture)
        if key not in known:
            print(f"note {sp['key']}: '{latin}' is not in tree_species.csv -> no rule")
            continue
        selectors = []
        for alt in [key] + syn.get(key, []):
            if alt == key and selectors:
                continue
            owner = claimed.get(alt)
            if owner and owner != latin:
                print(f"note {sp['key']}: synonym '{formatted(alt)}' already used "
                      f"by {owner}, skipped")
                continue
            claimed[alt] = latin
            selectors.append(formatted(alt))
        total_selectors += len(selectors)
        sel = ",\n".join(f'node[natural=tree][species="{s}"]' for s in selectors)
        mentry = manifest[texture[:-4]]
        wh = 10.0 * mentry["realWidthMeters"] / mentry["realHeightMeters"]
        rules.append(f"{sel} {{")
        rules.append(f'    billboard: "/textures/trees/{texture}";')
        rules.append("    height: 10;")
        rules.append(f"    width: {wh:.1f};")
        rules.append("}")
    rules.append(MARK_END)
    with open(ASSETS_TREES, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(rules) + "\n")
    print(f"textures available for the makefile copy step (*_{args.variant}.png): {len(textures)}")
    print(f"selectors: {total_selectors}, rules written: {ASSETS_TREES}")
    print("\nadd to AssetListTest MASTER_ASSET_LIST (provenance is a derivative of MIT):")
    for texture in textures:
        print(f'        MASTER_ASSET_LIST.put("/textures/trees/{texture}", new AssetInfo('
              '"https://github.com/SkyeShark/SeedThree", '
              '"SeedThree (SkyeShark), procedural render of its preset", "MIT license"));')


if __name__ == "__main__":
    main()
